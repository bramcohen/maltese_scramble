"""The subgroup data every table starts from (LADDER.md, "Building the tables"), written to tables/ (or $TABLES):

    bsgs_Y, bsgs_H1p, bsgs_H1, bsgs_A1, bsgs_F16   stabiliser chains of the subgroups given by generating words
    invisible_gens                                 generators of S: even permutations of same-coloured gears, centre spins
    bsgs_Z                                         Z = states of G with the equatorial gears on equatorial slots, the
                                                   top/bottom edges on top/bottom edge slots, every corner untwisted, and
                                                   the spins of the top/bottom edges summing to an even number of quarter
                                                   turns, as do the spins of the equatorial gears (from random elements
                                                   of that set; the order is checked by counting)
    bsgs_Y2                                        Y2 = <Y, S ∩ (the slot classes of Z)>, twice Y

The generating words are documented below and checked by fulltab/census.py.
A chain is {"gens": words, "perm_gens": permutations, "levels": [(base point, orbit, transversal) ...]} on the 192
(piece, orientation) points of groupfacts.py; coset.py labels right cosets with the levels.  Every chain, and the
tables built from it, must come from the same run: a rebuilt chain gives different labels.  About 10 minutes (sympy)."""
import os, sys, time, math, pickle, numpy as np, model as M, coset as CS
sys.path.insert(0, "."); import groupfacts as GF
from sympy.combinatorics import Permutation, PermutationGroup
from sympy.combinatorics.util import _distribute_gens_by_base, _orbits_transversals_from_bsgs
T0 = time.time(); log = lambda s: print(f"{s} ({time.time() - T0:.0f}s)", flush=True)
OUT = os.environ.get("TABLES", "tables"); os.makedirs(OUT, exist_ok=True)
# The generating words.  The subgroups are the ladder's (LADDER.md, "The ladder"); fulltab/census.py lists, for each
# pair of consecutive subgroups, the elements of the bigger one outside the smaller within 7 HTM, which is where the
# words below come from:
#   H1   <U, R2, F2>, the half-turn subgroup of the three faces that move.
#   A1   H1 with R and F restricted to full turns, plus R2 U2 R2 (the shortest elements of A1 outside F16 are the eight
#        words X2 Y2 X2 of 3 HTM; one of them with U, R4, F4 generates A1).
#   F16  U, R4, F4 and the eight relocated full turns X2 Y4 X2, X2 Y4 X'2: 393,216 states.
#   H1'  H1 plus all 24 elements of H1' \ H1 within 6 HTM: a quarter turn of R or F, a half turn of another axis, a full
#        turn of a third, the half turn undone, a quarter turn of the first face again (every such word is in H1').
#   Y    H1' plus one shortest element of Y \ H1' (7 HTM; there are 128, all equivalent for generating).
WORDS = {
    "H1": ["U", "R2", "F2"],
    "A1": ["U", "R4", "F4", "R2 U2 R2"],
    "F16": ["U", "R4", "F4", "R2 U4 R2", "R2 U4 R'2", "R2 F4 R2", "R2 F4 R'2", "F2 U4 F2", "F2 U4 F'2", "F2 R4 F2", "F2 R4 F'2"],
}
WORDS["H1p"] = WORDS["H1"] + [f"{a} {b}2 {c}4 {b}'2 {d}" for a in ("R", "R'", "F", "F'") for b in ("U", "R" if a[0] == "F" else "F")
                              for c in ("U", "R", "F") if c != b for d in ((a, a[0] + "'") if a in ("R", "F") else (a,))]
WORDS["Y"] = WORDS["H1p"][:3] + ["R U2 R2 U2 R2 U2 R"] + WORDS["H1p"][3:]
perm = lambda w: GF.perm_of(M.element(M.parse(w)))
st_perm = lambda st: GF.perm_of(st.as_element())

def chain(G, words, full_base=False):
    """The stabiliser chain of G in the format coset.py reads (trivial levels included).  full_base: the base is the
    192 points in order (the word-generated subgroups); else sympy's choice (Y2 and Z)."""
    if full_base: base, sg = G.schreier_sims_incremental(base=list(range(GF.NPTS)))
    else: G.schreier_sims(); base, sg = G.base, G.strong_gens
    dist = _distribute_gens_by_base(base, sg); orbs, trans = _orbits_transversals_from_bsgs(base, dist)
    levels = [(int(b), np.array(sorted(o), np.int64), np.array([tr[p].array_form for p in sorted(o)], np.uint8)) for b, o, tr in zip(base, orbs, trans)]
    return {"gens": words, "perm_gens": [g.array_form for g in G.generators], "levels": levels}

def save(name, d, order):
    pickle.dump(d, open(os.path.join(OUT, f"bsgs_{name}.pkl"), "wb"))
    log(f"bsgs_{name}: order {order:.6e}, {sum(1 for l in d['levels'] if len(l[1]) > 1)} nontrivial levels")


# ---- Z: generated by random elements of the set, checked against the count
UDE = [M.RING_NAMES.index(n) for n in ("UF", "UB", "UR", "UL", "DF", "DB", "DR", "DL")]
EQG = [M.GEAR_NAMES.index(n) for n in ("FR", "FL", "BR", "BL", "RF", "RB", "LF", "LB")]
isUD = np.zeros(18, np.int8); isUD[UDE] = 1; isEQ = np.zeros(24, np.int8); isEQ[EQG] = 1
Zspec = CS.Spec(pos={"r": (np.ones(18), isUD), "g": (np.ones(24), isEQ)}, fun={"c": (np.zeros(8, np.int8), np.eye(8, dtype=np.int8))})
kZ = Zspec.keys(CS.pack_states([M.State()]))[0]
UD = [i for i in range(18) if isUD[i]]; OT = [i for i in range(18) if not isUD[i]]; EQ = [i for i in range(24) if isEQ[i]]; TB = [i for i in range(24) if not isEQ[i]]
def in_Z(st):
    """The two spin conditions on top of the slot classes: even spin sums over the top/bottom edges and over the
    equatorial gears (the slot-class set without them is four times Z and is not reached by short sequences)."""
    return int(st.ro[UD].sum()) % 2 == 0 and int(st.go[EQ].sum()) % 2 == 0
def random_Z_state(rng):
    """A uniformly random element of Z (the construction of model.random_state within the slot classes, then the
    spin conditions by one quarter turn on a top/bottom edge or an equatorial gear, balanced elsewhere)."""
    cp = np.append(rng.permutation(7), 7).astype(np.int8); co = np.zeros(8, np.int8); cpar = M._parity(cp)
    rp = np.zeros(18, np.int8); rp[UD] = rng.permutation(UD); rp[OT] = rng.permutation(OT)
    if M._parity(rp): rp[[UD[0], UD[1]]] = rp[[UD[1], UD[0]]]
    ro = rng.integers(0, 4, 18).astype(np.int8)
    if int(ro[UD].sum()) % 2: ro[UD[0]] = (ro[UD[0]] + 1) % 4
    if (int(ro.sum()) + cpar) % 2: ro[OT[0]] = (ro[OT[0]] + 1) % 4
    gp = np.zeros(24, np.int8); gp[EQ] = rng.permutation(EQ); gp[TB] = rng.permutation(TB)
    if M._parity(gp) != cpar: gp[[EQ[0], EQ[1]]] = gp[[EQ[1], EQ[0]]]
    go = rng.integers(0, 4, 24).astype(np.int8)
    if int(go[EQ].sum()) % 2: go[EQ[0]] = (go[EQ[0]] + 1) % 4
    go[TB[0]] = (go[TB[0]] - int(go.sum())) % 4
    st = M.State(cp, co, rp, ro, gp, go); assert not M.check(st) and Zspec.keys(CS.pack_states([st]))[0] == kZ and in_Z(st)
    return st
oZ = math.factorial(7) * (math.factorial(8) * math.factorial(10) * 4 ** 18 // 4) * (math.factorial(8) * math.factorial(16) * 4 ** 24 // 8) // 4
if __name__ == "__main__":
    # ---- the word-generated subgroups
    groups = {}
    for name in ("H1", "A1", "F16", "H1p", "Y"):
        G = PermutationGroup([perm(w) for w in WORDS[name]]); groups[name] = G; save(name, chain(G, WORDS[name], full_base=True), G.order())
    # ---- S, the invisible subgroup: even permutations of the gears within each colour, centre spins with even sum
    col = {c: [p for p in range(24) if int(M.GEAR_COLOR[p]) == c] for c in range(6)}
    centres = [i for i in range(18) if M.IS_CENTER[i]]
    sg = []
    for c in range(6):
        a, b, d, e = col[c]
        for x, y, z in ((a, b, d), (b, d, e)):
            st = M.State(); st.gp[[x, y, z]] = st.gp[[y, z, x]]; sg.append(st_perm(st))
    for c in range(5):
        st = M.State(); a, b = col[c][:2]; d, e = col[c + 1][:2]; st.gp[[a, b]] = st.gp[[b, a]]; st.gp[[d, e]] = st.gp[[e, d]]; sg.append(st_perm(st))
    for i, j in zip(centres, centres[1:]):
        st = M.State(); st.ro[i] = 1; st.ro[j] = 3; sg.append(st_perm(st))
    st = M.State(); st.ro[centres[0]] = 2; sg.append(st_perm(st))
    S = PermutationGroup(sg); oS = math.factorial(4) ** 6 // 2 * 4 ** 6 // 2
    assert S.order() == oS, (S.order(), oS)
    pickle.dump([g.array_form for g in sg], open(os.path.join(OUT, "invisible_gens.pkl"), "wb")); log(f"invisible_gens: |S| = {oS:.6e} (37.5 bits), {len(sg)} generators")
    # ---- Z
    rng = np.random.default_rng(2026); zg = [st_perm(random_Z_state(rng)) for _ in range(24)]
    Z = PermutationGroup(zg); assert Z.order() == oZ, (Z.order(), oZ)          # G's five invariants within the slot classes, two spin parities
    save("Z", chain(Z, []), oZ)
    # ---- Y2 = <Y, S ∩ positions of Z>
    def pres(g):
        a = g.array_form
        return all(isEQ[(a[GF.G0 + i * 4] - GF.G0) // 4] == isEQ[i] for i in range(24)) and all(isUD[(a[GF.R0 + i * 4] - GF.R0) // 4] == isUD[i] for i in range(18))
    K = S.subgroup_search(pres); Y2 = PermutationGroup(list(groups["Y"].generators) + list(K.generators))
    assert Y2.order() == 2 * groups["Y"].order()
    save("Y2", chain(Y2, WORDS["Y"]), Y2.order())
    # ---- the Z chain labels right cosets Z.x: x and z.x share a label for z in Z, not for z in the slot-class set outside Z
    rng = np.random.default_rng(1); spZ = CS.Spec(canon=pickle.load(open(os.path.join(OUT, "bsgs_Z.pkl"), "rb"))); same = diff = 0
    for _ in range(2000):
        x = M.random_state(rng); z = random_Z_state(rng); zo = random_Z_state(rng); zo.ro[UD[0]] = (zo.ro[UD[0]] + 1) % 4; zo.ro[OT[0]] = (zo.ro[OT[0]] + 1) % 4
        a, b, c = spZ.keys(CS.pack_states([x, z.apply(x.as_element()), zo.apply(x.as_element())])); same += a == b; diff += a != c
    log(f"Z chain on 2,000 random states: label kept by Z elements {same}/2000, changed by the other slot-class elements {diff}/2000"); assert same == diff == 2000
    log("done")
